"""External validation of the ranking (Phase 12, step 7).

Three checks, none of which was used to set weights:
1. Blind holdout gold set (evals/gold/calibration_holdout.csv): expected tens in Tier 1, zeros in Tier 3.
2. Supplier finance programmes tagged in XBRL (data/interim/sfa_universe_tags.csv), SEC filers only
   (ESEF notes are block-tagged, so "not tagged" there means nothing): do Tier 1 accounts carry
   tagged programmes more often? Uses base_tier (before the signal upgrade), because the signal
   score includes confirmed supplier finance disclosures for the top 200.
3. Public vendor case studies (data/interim/public_scf_case_studies.csv, company_id column): companies a
   vendor of AP automation, dynamic discounting or supply chain finance names as a customer.

Stats: one-sided Fisher exact test (hypergeometric, no scipy needed) and a permutation test on the
difference in mean pain score (10,000 shuffles, seed 7). Writes evals/reports/external_validation_numbers.md.
Run: .venv/bin/python evals/external_validation.py
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "data" / "processed"


def fisher_greater(a: int, b: int, c: int, d: int) -> float:
    """P(X >= a) for the 2x2 table [[a, b], [c, d]] with fixed margins (one-sided, enrichment in row 1)."""
    r1, c1, n = a + b, a + c, a + b + c + d
    denom = math.comb(n, c1)
    return sum(math.comb(r1, k) * math.comb(n - r1, c1 - k) for k in range(a, min(r1, c1) + 1)) / denom


def odds_ratio(a, b, c, d) -> float:
    return (a + 0.5) * (d + 0.5) / ((b + 0.5) * (c + 0.5))   # Haldane correction


def perm_test(x: np.ndarray, y: np.ndarray, n: int = 10000, seed: int = 7) -> float:
    rng = np.random.default_rng(seed)
    obs = x.mean() - y.mean()
    pool = np.concatenate([x, y])
    k = len(x)
    hits = 0
    for _ in range(n):
        rng.shuffle(pool)
        if pool[:k].mean() - pool[k:].mean() >= obs:
            hits += 1
    return (hits + 1) / (n + 1)


def mantel_haenszel(df: pd.DataFrame, flag: str) -> tuple[float, str]:
    """Odds ratio of Tier 1 (base) vs flag, stratified by revenue tercile (size confounds tagging and fit)."""
    d = df[df.revenue_usd.notna()].copy()
    d["band"] = pd.qcut(d.revenue_usd.rank(method="first"), 3, labels=["small", "mid", "large"])
    num = den = 0.0
    parts = []
    for b, g in d.groupby("band", observed=True):
        t1, f = g.base_tier == 1, g[flag]
        a, bb, cc, dd, n = (t1 & f).sum(), (t1 & ~f).sum(), (~t1 & f).sum(), (~t1 & ~f).sum(), len(g)
        num += a * dd / n
        den += bb * cc / n
        parts.append(f"{b}: {f[t1].mean():.0%} of {int(t1.sum())} Tier 1 vs {f[~t1].mean():.0%} of {int((~t1).sum())} others")
    return (num / den if den else float("nan")), "; ".join(parts)


def enrichment(df: pd.DataFrame, flag: str, label: str) -> list[str]:
    t1, rest = df[df.base_tier == 1], df[df.base_tier > 1]
    a, b = int(t1[flag].sum()), int((~t1[flag]).sum())
    c, d = int(rest[flag].sum()), int((~rest[flag]).sum())
    p = fisher_greater(a, b, c, d)
    pp = perm_test(df[df[flag]].pain_score.to_numpy(float), df[~df[flag]].pain_score.to_numpy(float)) if df[flag].sum() else float("nan")
    return [f"| {label} | {len(df)} | {int(df[flag].sum())} | {a}/{len(t1)} = {a / max(len(t1), 1):.0%} | "
            f"{c}/{len(rest)} = {c / max(len(rest), 1):.0%} | {odds_ratio(a, b, c, d):.2f} | {p:.4f} | "
            f"{df[df[flag]].pain_score.mean():.1f} vs {df[~df[flag]].pain_score.mean():.1f} | {pp:.4f} |"]


def main() -> None:
    c = pd.read_parquet(P / "companies.parquet")
    L = ["# External validation: numbers", "",
         "Generated by `evals/external_validation.py`. Interpretation and caveats: `evals/reports/external_validation.md`.", ""]

    # 1. holdout
    h = pd.read_csv(ROOT / "evals" / "gold" / "calibration_holdout.csv")
    m = h.merge(c[["company_id", "priority_tier", "pain_basis"]], on="company_id", how="left")
    ct = pd.crosstab(m.expected, m.priority_tier)
    tens, zeros = m[m.expected == "ten"], m[m.expected == "zero"]
    L += ["## 1. Blind holdout (40 companies)", "",
          f"- Tens in Tier 1: {int((tens.priority_tier == 1).sum())}/{len(tens)}; tens in Tier 3: {int((tens.priority_tier == 3).sum())}.",
          f"- Zeros in Tier 3: {int((zeros.priority_tier == 3).sum())}/{len(zeros)}; zeros in Tier 1: {int((zeros.priority_tier == 1).sum())}.",
          f"- Severe misses (ten in Tier 3 or zero in Tier 1): {int((tens.priority_tier == 3).sum() + (zeros.priority_tier == 1).sum())}/40.",
          "", "| expected \\ tier | " + " | ".join(str(x) for x in ct.columns) + " |", "|---|" + "---:|" * len(ct.columns)]
    L += [f"| {i} | " + " | ".join(str(int(v)) for v in r) + " |" for i, r in ct.iterrows()]
    miss = m[((m.expected == "ten") & (m.priority_tier != 1)) | ((m.expected == "zero") & (m.priority_tier != 3))]
    L += ["", "Misses: " + "; ".join(f"{r.name} ({r.expected}, Tier {int(r.priority_tier)}, {r.pain_basis})" for r in miss.itertuples()), ""]

    # 2 + 3 enrichment tables
    hdr = ["| Test | n | positives | rate in Tier 1 (base) | rate in Tier 2-3 | odds ratio | Fisher p (one-sided) | mean pain: positive vs not | permutation p |",
           "|---|---:|---:|---|---|---:|---:|---|---:|"]
    acc = c[c.excluded_reason.isna()].copy()
    t = pd.read_csv(ROOT / "data" / "interim" / "sfa_universe_tags.csv")
    sec_ids = set(t.loc[t.status.isin(["tagged", "not_tagged"]) & t.source_url.astype(str).str.contains("sec.gov"), "company_id"])
    s = acc[acc.company_id.isin(sec_ids)].merge(t[["company_id", "status"]], on="company_id")
    s["sf_tagged"] = s.status == "tagged"
    L += ["## 2. Supplier finance programme tagged in SEC XBRL", ""] + hdr
    L += enrichment(s, "sf_tagged", "all SEC filers")
    for basis, lab in (("uk_reported", "pain from UK reported days"), ("computed_dpo_proxy", "pain from computed DPO")):
        L += enrichment(s[s.pain_basis == basis], "sf_tagged", lab)
    for lab, sub in (("all SEC filers", s), ("pain from UK reported days", s[s.pain_basis == "uk_reported"])):
        orr, parts = mantel_haenszel(sub, "sf_tagged")
        L += [f"- Size-adjusted (revenue terciles, Mantel-Haenszel) odds ratio, {lab}: **{orr:.2f}**. {parts}."]
    L += [""]

    cs_p = ROOT / "data" / "interim" / "public_scf_case_studies.csv"
    cs = pd.read_csv(cs_p) if cs_p.exists() else pd.DataFrame()
    L += ["## 3. Named customer of an AP / early-payment / supply chain finance vendor", ""]
    if "company_id" in cs and cs.company_id.notna().any():
        strict = cs[cs.evidence_year.fillna(0) != 2012]          # drop the 2012 gov.uk pledge list (intent, not a programme)
        ids_all, ids = set(cs.company_id.dropna()), set(strict.company_id.dropna())
        acc["case_study"] = acc.company_id.isin(ids)
        acc["case_study_incl_2012"] = acc.company_id.isin(ids_all)
        L += hdr + enrichment(acc, "case_study", "all scored accounts (strict: 2012 pledge list dropped)")
        for basis, lab in (("uk_reported", "pain from UK reported days"), ("computed_dpo_proxy", "pain from computed DPO")):
            L += enrichment(acc[acc.pain_basis == basis], "case_study", f"{lab} (strict)")
        L += enrichment(acc, "case_study_incl_2012", "all scored accounts (incl. 2012 pledge list)")
        orr, parts = mantel_haenszel(acc, "case_study")
        L += ["", f"- Size-adjusted odds ratio (strict): **{orr:.2f}**. {parts}.",
              f"- Matched companies among scored accounts: strict {len(ids & set(acc.company_id))}, incl. 2012 {len(ids_all & set(acc.company_id))}; "
              f"named on the list: {cs.company.nunique()}."]
    else:
        L += ["No matched case-study list yet."]
    out = ROOT / "evals" / "reports" / "external_validation_numbers.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
