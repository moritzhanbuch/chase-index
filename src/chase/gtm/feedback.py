"""Feedback loop: which score components separate meetings from rejections?

Reads the status file (config/status/accounts_status.csv; --demo reads the SYNTHETIC demo outcomes),
keeps the newest status per account and compares two groups:
  positive = meeting or won        negative = lost or not_a_fit
"contacted" has no outcome yet and is ignored.

Method (deliberately simple; this is for dozens of outcomes, not thousands):
- per component (fit, pain, signal, priority score and their parts): mean in each group, Cohen's d
  (difference in means over the pooled standard deviation) and AUC (the probability that a random
  positive account scores higher than a random negative one; 0.5 = no separation), with a
  bootstrap 90% interval for the AUC (2,000 resamples, fixed seed).
- nothing is refitted automatically. The report tells a human which weights to look at.
- below 20 outcomes, or with fewer than 5 in either group, it refuses to report numbers.

  python -m chase.gtm.feedback          # your outcomes
  python -m chase.gtm.feedback --demo   # SYNTHETIC outcomes, to show the report
Writes evals/reports/feedback_report.md (or feedback_report_demo.md).
"""
from __future__ import annotations

import json
import sys

import numpy as np
import pandas as pd

from chase import query as q
from chase.gtm import byod

MIN_OUTCOMES, MIN_PER_GROUP = 20, 5
POS, NEG = {"meeting", "won"}, {"lost", "not_a_fit"}


def auc(pos: np.ndarray, neg: np.ndarray) -> float:
    """Mann-Whitney AUC with ties counted as half."""
    gt = (pos[:, None] > neg[None, :]).sum()
    eq = (pos[:, None] == neg[None, :]).sum()
    return float((gt + 0.5 * eq) / (len(pos) * len(neg)))


def cohens_d(pos: np.ndarray, neg: np.ndarray) -> float:
    n1, n2 = len(pos), len(neg)
    sp = np.sqrt(((n1 - 1) * pos.var(ddof=1) + (n2 - 1) * neg.var(ddof=1)) / (n1 + n2 - 2))
    return float((pos.mean() - neg.mean()) / sp) if sp > 0 else 0.0


def analyse(demo: bool = False) -> dict:
    flags, _ = byod.apply(demo)
    comp = q.companies().set_index("company_id")
    rows = []
    for cid, fl in flags.items():
        st = fl.get("status")
        if not st or cid not in comp.index:
            continue
        label = 1 if st["status"] in POS else 0 if st["status"] in NEG else None
        if label is None:
            continue
        r = comp.loc[cid]
        feats = {"fit_score": r.fit_score, "pain_score": r.pain_score, "signal_score": r.signal_score, "priority_score": r.priority_score}
        feats.update({f"fit:{k}": v for k, v in json.loads(r.fit_parts).items()})
        feats.update({f"pain:{k}": v for k, v in json.loads(r.pain_parts).items() if isinstance(v, (int, float)) and "factor" not in k and "ratio" not in k})
        rows.append({"company_id": cid, "label": label, "reason": st.get("reason", ""), "status": st["status"], **feats})
    df = pd.DataFrame(rows)
    n_pos, n_neg = int((df.label == 1).sum()) if len(df) else 0, int((df.label == 0).sum()) if len(df) else 0
    out = {"mode": "SYNTHETIC demo outcomes" if demo else "local status file", "outcomes": len(df), "positive": n_pos, "negative": n_neg,
           "enough": len(df) >= MIN_OUTCOMES and min(n_pos, n_neg) >= MIN_PER_GROUP, "components": [], "reasons": {}}
    if not out["enough"]:
        return out
    rng = np.random.default_rng(20261116)
    for col in [c for c in df.columns if c not in ("company_id", "label", "reason", "status")]:
        x = df[col].astype(float)
        if x.notna().sum() < len(df) * 0.8 or x.nunique() < 2:
            continue
        x = x.fillna(0.0)
        pos, neg = x[df.label == 1].to_numpy(), x[df.label == 0].to_numpy()
        boots = [auc(rng.choice(pos, len(pos)), rng.choice(neg, len(neg))) for _ in range(2000)]
        out["components"].append({"component": col, "mean_meetings": round(pos.mean(), 1), "mean_rejections": round(neg.mean(), 1),
                                  "cohens_d": round(cohens_d(pos, neg), 2), "auc": round(auc(pos, neg), 2),
                                  "auc_90_low": round(float(np.quantile(boots, 0.05)), 2), "auc_90_high": round(float(np.quantile(boots, 0.95)), 2)})
    out["components"].sort(key=lambda c: -abs(c["auc"] - 0.5))
    out["reasons"] = df[df.label == 0].reason.value_counts().head(8).to_dict()
    return out


def report(res: dict, demo: bool) -> str:
    L = ["# Feedback report: what separates meetings from rejections", "", f"_{q.DISCLAIMER}_", ""]
    if demo:
        L += ["**SYNTHETIC DEMO.** The outcomes below were generated by a formula that rewards pain and signal scores "
              "(`config/status/demo_accounts_status.csv`). They show what the report looks like. They are not real outreach results, "
              "and the separation you see is the formula coming back out.", ""]
    L += [f"Outcomes: {res['outcomes']} ({res['positive']} meeting or won, {res['negative']} lost or not a fit). Source: {res['mode']}.", ""]
    if not res["enough"]:
        L += [f"Not enough outcomes yet. The report needs at least {MIN_OUTCOMES} outcomes with at least {MIN_PER_GROUP} in each group. "
              "Keep appending rows to `config/status/accounts_status.csv`."]
        return "\n".join(L) + "\n"
    L += ["Method: per score component, the mean in each group, Cohen's d and AUC with a bootstrap 90% interval. AUC 0.5 means the component "
          "does not separate the groups; an interval that includes 0.5 means you cannot tell yet. Nothing is refitted automatically.", "",
          "| Component | Mean, meetings | Mean, rejections | Cohen's d | AUC | 90% interval |", "|---|---|---|---|---|---|"]
    for c in res["components"]:
        L.append(f"| {c['component']} | {c['mean_meetings']} | {c['mean_rejections']} | {c['cohens_d']} | {c['auc']} | {c['auc_90_low']} to {c['auc_90_high']} |")
    clear = [c["component"] for c in res["components"] if c["auc_90_low"] > 0.5 or c["auc_90_high"] < 0.5]
    L += ["", "Components whose interval excludes 0.5: " + (", ".join(clear) if clear else "none yet") + ".", "",
          "What to do with it: raise the weight of a component that clearly separates, question one that points the wrong way (AUC below 0.5), "
          "and read the rejection reasons before touching any weight. With a few dozen outcomes this is a prompt for judgement, not a model.", "",
          "## Rejection reasons", ""] + [f"- {k}: {v}" for k, v in res["reasons"].items()]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    demo = "--demo" in sys.argv
    res = analyse(demo)
    path = q.ROOT / "evals" / "reports" / ("feedback_report_demo.md" if demo else "feedback_report.md")
    path.write_text(report(res, demo))
    print(f"{res['outcomes']} outcomes, enough={res['enough']} -> {path.relative_to(q.ROOT)}")
    for c in res["components"][:5]:
        print(" ", c)
